// Writes css/themes.css from js/palettes.js. Run: node tools/build-themes.mjs
// With --check, exits non-zero if the file is out of date or a palette fails its contrast checks.
import {readFileSync, writeFileSync} from 'node:fs';
import {PALETTES} from '../js/palettes.js';

const VARS = {bg: '--bg', panel: '--panel', raise: '--raise', ink: '--ink', muted: '--muted', line: '--line', accent: '--accent', onAccent: '--on-accent', listen: '--listen', speak: '--speak', alert: '--alert'};
const decl = t => Object.entries(VARS).map(([k, v]) => `${v}:${t[k]}`).join('; ');

export function buildCSS() {
  let css = '/* Generated by tools/build-themes.mjs from js/palettes.js. Do not edit by hand. */\n';
  for (const p of PALETTES) {
    const sel = p.id === PALETTES[0].id ? `:root, :root[data-palette="${p.id}"]` : `:root[data-palette="${p.id}"]`;
    const light = p.id === PALETTES[0].id ? `:root:not([data-palette]), :root[data-palette="${p.id}"]` : `:root[data-palette="${p.id}"]`;
    css += `${sel}{${decl(p.dark)}; color-scheme:dark}\n`;
    css += `@media (prefers-color-scheme: light){${light.split(', ').map(s => s + ':not([data-theme="dark"])').join(', ')}{${decl(p.light)}; color-scheme:light}}\n`;
    css += `${light.split(', ').map(s => s + '[data-theme="light"]').join(', ')}{${decl(p.light)}; color-scheme:light}\n`;
  }
  return css;
}

// WCAG contrast
const lum = hex => { const c = hex.slice(1).match(/../g).map(h => parseInt(h, 16) / 255).map(v => v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4); return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]; };
export const contrast = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m); return (x + 0.05) / (y + 0.05); };
export function checkContrast() {
  const fails = [];
  for (const p of PALETTES) for (const mode of ['dark', 'light']) {
    const t = p[mode];
    const need = [
      ['ink on bg', t.ink, t.bg, 7], ['ink on panel', t.ink, t.panel, 7], ['ink on raise', t.ink, t.raise, 7],
      ['muted on bg', t.muted, t.bg, 4.5], ['muted on panel', t.muted, t.panel, 4.5], ['muted on raise', t.muted, t.raise, 4.5],
      ['accent text on bg', t.accent, t.bg, 4.5], ['accent text on panel', t.accent, t.panel, 4.5],
      ['onAccent on accent', t.onAccent, t.accent, 4.5],
      ['alert on raise', t.alert, t.raise, 4.5], ['listen ring on bg', t.listen, t.bg, 3], ['speak dot on raise', t.speak, t.raise, 3]
    ];
    for (const [what, fg, bg, min] of need) { const r = contrast(fg, bg); if (r < min) fails.push(`${p.name} ${mode}: ${what} ${r.toFixed(2)} < ${min}`); }
  }
  return fails;
}

const path = new URL('../css/themes.css', import.meta.url);
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  const fails = checkContrast();
  if (fails.length) { console.error(fails.join('\n')); process.exitCode = 1; }
  const css = buildCSS();
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== css) { console.error('css/themes.css is out of date; run node tools/build-themes.mjs'); process.exitCode = 1; }
  } else { writeFileSync(path, css); console.log('wrote css/themes.css'); }
}
